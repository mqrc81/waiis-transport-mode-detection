"""Stop-point 3 tables from the exported runs (results/runs.csv): results/tables/test.md. Mean of seeds 0-2, each
seed's value and CI alongside.

    uv run python tables_test.py
"""
from __future__ import annotations

from pathlib import Path

import numpy as np
import pandas as pd

HERE = Path(__file__).resolve().parent
CFG = ("E2", "A0", "E1")


def main():
    r = pd.read_csv(HERE / "results" / "runs.csv")
    r = r[r.row.astype(str).str.startswith("test_")].copy()
    r["cfg"] = r.row.str.removeprefix("test_")
    r = r.sort_values(["cfg", "seed"])
    tram_as = [c for c in r.columns if c.startswith("test_nor_tram_as_")]
    r[tram_as] = r[tram_as].fillna(0)                   # a class no tram minute went to in that seed: 0 minutes

    def vals(cfg, k):
        d = r[r.cfg == cfg]
        return d[k].to_numpy(float) if k in d and d[k].notna().any() else None

    def cell(cfg, k, d=3, ci=True):
        v = vals(cfg, k)
        if v is None:
            return "–"
        s = f"**{np.mean(v):.{d}f}**"
        if ci and vals(cfg, k + "_lo") is not None:
            lo, hi = vals(cfg, k + "_lo"), vals(cfg, k + "_hi")
            s += " (" + "; ".join(f"{a:.{d}f} [{b:.{d}f}, {c:.{d}f}]" for a, b, c in zip(v, lo, hi)) + ")"
        elif len(v) > 1:
            s += " (" + " / ".join(f"{a:.{d}f}" for a in v) + ")"
        return s

    def table(rows, cols):
        return "| " + " | ".join(cols) + " |\n|" + "---|" * len(cols) + "\n" + \
            "\n".join("| " + " | ".join(map(str, x)) + " |" for x in rows) + "\n"

    md = ["# 10 test (generated by tables_test.py from results/runs.csv)\n",
          "Bold: mean of seeds 0-2; in brackets each seed (with its 95% user-bootstrap CI where there is one).\n"]
    md.append("## ExtraSensory test, 12 users (E2 final, A0 reference)\n")
    rows = []
    for plat in ("all", "iphone", "android"):
        for lvl in ("six", "fine", "family"):
            rows.append([plat, lvl, cell("E2", f"test_es_{plat}_{lvl}_f1"), cell("A0", f"test_es_{plat}_{lvl}_f1"),
                         cell("E2", f"test_es_{plat}_{lvl}_f1_diff_A0")])
    md.append(table(rows, ["Platform", "Level", "E2", "A0", "E2 − A0 (paired)"]))
    md.append("\nSix-class by GPS coverage: " + "; ".join(
        f"{p} {c}: E2 {cell('E2', f'test_es_{p}_{c}_six_f1', ci=False)}, A0 {cell('A0', f'test_es_{p}_{c}_six_f1', ci=False)}"
        for p in ("iphone", "android") for c in ("covered", "uncovered")) + "\n")

    md.append("\n## ExtraSensory test per class (9-class recall, six-class precision)\n")
    rows = [[c, cell("E2", f"test_es_all_fine_recall_{c}", 2), cell("A0", f"test_es_all_fine_recall_{c}", 2)]
            for c in ("still", "walk", "run", "bike", "car", "bus", "train")]
    md.append(table(rows, ["Class", "E2 recall", "A0 recall"]))
    rows = [[c, cell("E2", f"test_es_all_six_precision_{c}", 2, False), cell("A0", f"test_es_all_six_precision_{c}", 2, False)]
            for c in ("still", "foot", "bike", "car", "bus", "rail")]
    md.append("\n" + table(rows, ["Class", "E2 precision", "A0 precision"]))
    md.append(f"\nWalk → still minutes: E2 {cell('E2', 'test_es_walk_to_still', 0, False)}, "
              f"A0 {cell('A0', 'test_es_walk_to_still', 0, False)}.\n")

    md.append("\n## NOR-TMD test, 14 installations\n")
    rows = [[c, cell(c, "test_nor_guard_six_f1"), cell(c, "test_nor_guard_six_f1_diff_A0")] for c in CFG]
    md.append(table(rows, ["Model", "bus / car / rail macro-F1", "− A0 (paired)"]))
    rows = [[k] + [cell(c, f"test_nor_fine_recall_{k}", 2) for c in CFG] for k in ("bus", "subway", "train", "tram", "car")]
    md.append("\n" + table(rows, ["9-class recall"] + list(CFG)))
    tram = sorted({c.removeprefix("test_nor_tram_as_") for c in r.columns if c.startswith("test_nor_tram_as_")})
    rows = [[k] + [cell(c, f"test_nor_tram_as_{k}", 0, False) for c in CFG] for k in tram]
    md.append("\nNOR-TMD tram minutes predicted as:\n\n" + table(rows, ["Predicted"] + list(CFG)))

    md.append("\n## SHL Users 2–3 rail check, per position (no CI)\n")
    rows = []
    for pos in ("hips", "hand", "torso", "bag"):
        for c in CFG:
            rows.append([pos, c, cell(c, f"test_shl23_{pos}_six_f1", ci=False), cell(c, f"test_shl23_{pos}_fine_f1", ci=False),
                         cell(c, f"test_shl23_{pos}_family_f1", ci=False),
                         cell(c, f"test_shl23_{pos}_fine_recall_train", 2, False) + " / " +
                         cell(c, f"test_shl23_{pos}_fine_recall_train_before_hmm", 2, False),
                         cell(c, f"test_shl23_{pos}_fine_recall_subway", 2, False) + " / " +
                         cell(c, f"test_shl23_{pos}_fine_recall_subway_before_hmm", 2, False)])
    md.append(table(rows, ["Position", "Model", "six", "9-class", "family", "train recall (after / before HMM)",
                           "subway recall (after / before HMM)"]))

    md.append("\n## Cost\n")
    rows = [[c, cell(c, "lat_inference_ms_p50", 1, False), cell(c, "lat_inference_ms_p95", 1, False),
             cell(c, "lat_pipeline_ms_p50", 2, False), cell(c, "lat_pipeline_ms_p95", 2, False),
             f"{np.mean(vals(c, 'acc_model_bytes')) / 1e6:.2f}", f"{np.mean(vals(c, 'gps_model_bytes')) / 1e6:.2f}"]
            for c in CFG]
    md.append(table(rows, ["Model", "1 window p50 [ms]", "p95", "per window, sessions p50", "p95", "acc model [MB]",
                           "GPS model [MB]"]))
    out = HERE / "results" / "tables" / "test.md"
    out.write_text("\n".join(md))
    print(f"-> {out}")


if __name__ == "__main__":
    main()
