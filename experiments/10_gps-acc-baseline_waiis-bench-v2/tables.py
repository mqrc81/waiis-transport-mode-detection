"""Stop-point 2 tables from MLflow (seed 0 rows): results/tables/ablation.md.

    uv run python tables.py                       # rows A0 A1 A2 S P (+ R06)
"""
from __future__ import annotations

import argparse
from pathlib import Path

import mlflow
import pandas as pd

from tmd.tracking import TRACKING_URI

HERE = Path(__file__).resolve().parent
EXP = HERE.name
SIX = ["still", "foot", "bike", "car", "bus", "rail"]


def runs(names) -> dict[str, pd.Series]:
    mlflow.set_tracking_uri(TRACKING_URI)
    r = mlflow.search_runs(experiment_names=[EXP])
    out = {}
    for n in names:
        d = r[r["tags.mlflow.runName"] == n].sort_values("start_time")
        if len(d):
            s = d.iloc[-1]
            out[n.rsplit("_seed", 1)[0]] = pd.Series({k[8:]: v for k, v in s.items()
                                                       if k.startswith("metrics.") and v == v})
    return out


def f(v, d=3):
    return "–" if v != v else f"{v:.{d}f}"


def ci(m, k, d=3):
    return f"{f(m.get(k, float('nan')), d)} [{f(m.get(k + '_lo', float('nan')), d)}, {f(m.get(k + '_hi', float('nan')), d)}]"


def diff(m, k, b, d=3):
    kk = f"{k}_diff_{b}" if not k.endswith("_f1") else f"{k}_diff_{b}"
    if kk not in m:
        return "–"
    return f"{m[kk]:+.{d}f} [{m.get(kk + '_lo', float('nan')):+.{d}f}, {m.get(kk + '_hi', float('nan')):+.{d}f}]"


def table(rows, cols) -> str:
    h = "| " + " | ".join(cols) + " |\n|" + "---|" * len(cols) + "\n"
    return h + "\n".join("| " + " | ".join(str(c) for c in r) + " |" for r in rows) + "\n"


def precision_diff(m, c, b="A0"):
    k = f"es_six_precision_{c}_diff_{b}"
    return "–" if k not in m else f"{m[k]:+.3f} [{m[k + '_lo']:+.3f}, {m[k + '_hi']:+.3f}]"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--rows", nargs="+", default=["R06", "A0", "A1", "A2", "S", "P", "E1", "E2"])
    a = ap.parse_args()
    R = runs([f"{r}_seed0" for r in a.rows])
    md = ["# 10 ablation tables (seed 0; generated by tables.py from MLflow)\n"]

    md.append("## Scores\n")
    md.append(table([[n, ci(m, "es_six_f1"), diff(m, "es_six_f1", "A0"), f(m.get("es_fine_f1", float("nan"))),
                      f(m.get("es_family_f1", float("nan"))), ci(m, "nor_guard_six_f1"),
                      diff(m, "nor_guard_six_f1", "A0"), f(m.get("collecty_six_f1", float("nan"))),
                      f(m.get("shl_six_f1", float("nan")))] for n, m in R.items()],
                    ["Row", "ES dev six-class [CI]", "vs A0 [paired CI]", "ES 9-class", "ES family",
                     "NOR-TMD guard [CI]", "vs A0 [paired CI]", "Collecty six", "SHL U1 six (day folds)"]))

    md.append("\n## (a) ExtraSensory dev six-class precision (difference vs A0, paired CI)\n")
    md.append(table([[n] + [f"{f(m.get(f'es_six_precision_{c}', float('nan')))} ({precision_diff(m, c)})"
                            for c in SIX] for n, m in R.items()], ["Row"] + SIX))
    md.append("\n9-class walk precision (descriptive): " + ", ".join(
        f"{n} {f(m.get('es_fine_precision_walk', float('nan')))}" for n, m in R.items()) + "\n")

    md.append("\n## (b) NOR-TMD transfer and per class (9-class recall)\n")
    cls = ["bus", "car", "train", "subway", "tram", "bike"]
    md.append(table([[n, f(m.get("nor_guard_six_f1", float("nan")))] +
                     [ci(m, f"nor_fine_recall_{c}", 2) for c in cls] for n, m in R.items() if n != "R06"],
                    ["Row", "guard"] + cls))

    md.append("\n## Recall with CIs, ExtraSensory dev (9-class)\n")
    cls = ["still", "walk", "run", "bike", "car", "bus", "train"]
    md.append(table([[n] + [ci(m, f"es_fine_recall_{c}", 2) for c in cls] for n, m in R.items()], ["Row"] + cls))

    md.append("\n## (c) Recall per source and class (9-class, official dev minutes)\n")
    srcs = ["extrasensory", "shl_user1", "nor_tmd", "collecty", "shl_user1_other"]
    fine = ["still", "walk", "run", "bike", "car", "bus", "train", "subway", "tram"]
    for n, m in R.items():
        if n == "R06":
            continue
        md.append(f"\n**{n}**\n\n" + table([[s] + [f(m.get(f"src_recall_{s}_{c}", float("nan")), 2) for c in fine]
                                            for s in srcs], ["Source"] + fine))

    md.append("\n## (d) Source identification within class (AUC; 09's windows)\n")
    rows = []
    for c in ["bus", "car", "train", "subway", "tram"]:
        r0 = next(iter(R.values()))
        rows.append([c, f(R.get("A0", r0).get(f"id_auc_features_09_{c}", float("nan")))] +
                    [" / ".join(f(m.get(f"id_auc_{k}_{c}", float("nan")), 2) for k in ("acc", "final", "final_uncovered"))
                     for n, m in R.items() if n != "R06"])
    md.append(table(rows, ["Class", "09 features"] + [f"{n}: acc / final / final no GPS" for n in R if n != "R06"]))

    md.append("\n## Tram predicted where there is none\n")
    md.append(table([[n] + [f"{int(m.get(f'tram_pred_{s}_usable_n', 0))} ({100 * m.get(f'tram_pred_{s}_usable_share', 0):.2f}%)"
                            for s in ("extrasensory", "shl_user1", "shl_user1_other")] for n, m in R.items()
                     if n != "R06"],
                    ["Row", "ExtraSensory usable", "SHL U1 hips usable", "SHL U1 other positions usable"]))

    md.append("\n## Unseen positions: SHL User 1 held-out days (six-class / 9-class)\n")
    md.append(table([[n] + [f"{f(m.get(f'shlpos_{p}_six_f1', float('nan')))} / {f(m.get(f'shlpos_{p}_fine_f1', float('nan')))}"
                            for p in ("hand", "torso", "bag")] for n, m in R.items() if n != "R06"],
                    ["Row", "hand", "torso", "bag"]))

    md.append("\n## HMM: transition-matrix diagonal; labelled transitions per source\n")
    md.append(table([[n] + [f(m.get(f"hmm_diag_{c}", float("nan")), 4) for c in fine] for n, m in R.items()
                     if n != "R06"], ["Row"] + fine))
    md.append("\n" + table([[n] + [f"{int(m[f'hmm_transitions_{s}'])} / {int(m[f'hmm_steps_{s}'])}"
                                   if f"hmm_transitions_{s}" in m else "–" for s in srcs[:4]]
                            for n, m in R.items() if n != "R06"], ["Row (mode changes / steps)"] + srcs[:4]))

    md.append("\n## Training weight share per class (acc model)\n")
    for n in R:
        p = HERE / "results" / "tables" / f"{n}_seed0" / "weight_share_acc.csv"
        if p.exists():
            w = pd.read_csv(p, index_col=0).round(3)
            md.append(f"\n**{n}**\n\n" + table([[i] + list(r) for i, r in w.iterrows()], ["class"] + list(w.columns)))

    md.append("\n## Cost\n")
    md.append(table([[n, f(m.get("lat_inference_ms_p50", float("nan")), 1), f(m.get("lat_inference_ms_p95", float("nan")), 1),
                      f(m.get("lat_pipeline_ms_p50", float("nan")), 2), f(m.get("lat_pipeline_ms_p95", float("nan")), 2),
                      f(m.get("acc_model_bytes_mean", float("nan")) / 1e6, 2),
                      f(m.get("gps_model_bytes_mean", float("nan")) / 1e6, 2), f(m.get("acc_rounds_mean", float("nan")), 0)]
                     for n, m in R.items() if n != "R06"],
                    ["Row", "1 window p50 [ms]", "p95", "per window, sessions p50", "p95", "acc model [MB]",
                     "GPS model [MB]", "acc rounds (mean)"]))
    out = HERE / "results" / "tables" / "ablation.md"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(md))
    print(f"-> {out}")


if __name__ == "__main__":
    main()
